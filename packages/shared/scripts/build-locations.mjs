// Builds src/generated/locations.js from the vendored geo dataset.
// Source: https://github.com/nuhil/bangladesh-geocode (MIT, see data/geo/LICENSE).
// Run with `npm run geo:build` after updating the JSON files in data/geo.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => {
  const raw = JSON.parse(fs.readFileSync(path.join(root, 'data/geo', f), 'utf8'));
  const table = raw.find((x) => x && x.type === 'table');
  return table ? table.data : raw;
};

// Modern official spellings for slugs and English labels.
const DIVISION_FIX = { Chattagram: 'Chattogram', Barisal: 'Barishal' };
const DISTRICT_FIX = {
  Comilla: 'Cumilla',
  Coxsbazar: "Cox's Bazar",
  Barisal: 'Barishal',
  Jhalakathi: 'Jhalokati',
  Chapainawabganj: 'Chapai Nawabganj',
};

// Old spellings inside upazila names, and typos in the source dataset.
const UPAZILA_WORD_FIX = {
  Barisal: 'Barishal',
  Comilla: 'Cumilla',
  Jessore: 'Jashore',
  Bogra: 'Bogura',
  Jhalakathi: 'Jhalokati',
  Coxsbazar: "Cox's Bazar",
  Chittagong: 'Chattogram',
};
const UPAZILA_FIX = { 'Borhan Sddin': 'Borhan Uddin', Sadarsouth: 'Sadar South', Charfesson: 'Char Fasson' };
const upazilaName = (name) => {
  const fixed = UPAZILA_FIX[name] || name;
  return fixed.replace(/\b[A-Z][a-z]+\b/g, (w) => UPAZILA_WORD_FIX[w] || w);
};

const slug = (s) =>
  s
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const divisions = read('divisions.json');
const districts = read('districts.json');
const upazilas = read('upazilas.json');

const out = divisions
  .map((d) => {
    const en = DIVISION_FIX[d.name] || d.name;
    return {
      value: slug(en),
      en,
      bn: d.bn_name,
      districts: districts
        .filter((x) => x.division_id === d.id)
        .map((x) => {
          const den = DISTRICT_FIX[x.name] || x.name;
          const dslug = slug(den).replace(/-/g, '');
          return {
            value: dslug,
            en: den,
            bn: x.bn_name,
            upazilas: upazilas
              .filter((u) => u.district_id === x.id)
              .map((u) => {
                const en = upazilaName(u.name);
                return { value: `${dslug}-${slug(en)}`, en, bn: u.bn_name };
              })
              .sort((a, b) => a.en.localeCompare(b.en)),
          };
        })
        .sort((a, b) => a.en.localeCompare(b.en)),
    };
  })
  .sort((a, b) => a.en.localeCompare(b.en));

const counts = out.reduce(
  (acc, d) => ({
    districts: acc.districts + d.districts.length,
    upazilas: acc.upazilas + d.districts.reduce((n, x) => n + x.upazilas.length, 0),
  }),
  { districts: 0, upazilas: 0 }
);

const target = path.join(root, 'src/generated/locations.js');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(
  target,
  `// GENERATED by scripts/build-locations.mjs — do not edit by hand.\n` +
    `// Data: nuhil/bangladesh-geocode (MIT). ${out.length} divisions, ${counts.districts} districts, ${counts.upazilas} upazilas.\n` +
    `export const DIVISIONS = ${JSON.stringify(out)};\n`
);
console.log(
  `Wrote ${path.relative(root, target)}: ${out.length} divisions, ${counts.districts} districts, ${counts.upazilas} upazilas`
);
